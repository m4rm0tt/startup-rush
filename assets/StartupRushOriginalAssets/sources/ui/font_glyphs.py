def _base(ch):
    if ch == 'ı':
        return DOTLESS_I
    return G[ch]


def compose(ch):
    """Construit (top, rangees) pour une lettre accentuee."""
    base, mark = COMPOSE[ch]
    top, rows = _base(base)
    w = max(len(r) for r in rows) if rows else 0
    upper = top <= 3
    if mark == 'cedilla':
        mid = w // 2
        extra = ['.' * mid + '#' + '.' * (w - mid - 1), '.' * (mid - 1) + '#' + '.' * (w - mid)]
        return top, rows + extra
    if mark in ('circ', 'diaer'):
        mk = MARKS[mark + ('4' if w % 2 == 0 and w >= 4 else '3')]
    else:
        mk = MARKS[mark]
    mw = len(mk[0])
    if mw > w:  # i sans point : on elargit le glyphe
        pad = (mw - w) // 2
        rows = ['.' * pad + r + '.' * (mw - w - pad) for r in rows]
        w = mw
    if mark == 'acute':
        off = (w - mw + 1) // 2
    else:
        off = (w - mw) // 2
    mrows = ['.' * off + r + '.' * (w - mw - off) for r in mk]
    mark_top = (1 if upper else 3) if len(mk) == 1 else (0 if upper else 2)
    # assemble de mark_top a la fin de la base
    out = []
    for y in range(mark_top, top + len(rows)):
        if mark_top <= y < mark_top + len(mrows):
            out.append(mrows[y - mark_top])
        elif y >= top:
            out.append(rows[y - top])
        else:
            out.append('.' * w)
    return mark_top, out


def all_glyphs(mono=False):
    """Dictionnaire complet caractere -> (top, rangees), accents composes."""
    d = dict(G)
    for ch in COMPOSE:
        d[ch] = compose(ch)
    if mono:
        d.update(MONO_OVERRIDE)
    return d


def advance_of(ch, rows, mono=False):
    if mono:
        return MONO_ADVANCE
    if ch == ' ':
        return SPACE_ADVANCE
    if ch == ' ':
        return SPACE_ADVANCE
    if ch == ' ':
        return 2
    if ch.isdigit():
        return DIGIT_ADVANCE
    w = max((len(r) for r in rows), default=0)
    return w + 1
